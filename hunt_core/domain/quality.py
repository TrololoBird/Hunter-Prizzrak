"""Качество данных: отличить «данных нет» от «код сломан».

ЗАЧЕМ ЭТОТ МОДУЛЬ СУЩЕСТВУЕТ. Это не абстракция ради стройности, а ответ на измеренный
инцидент, описанный в самом дереве (`prizrak/orchestrator.py::526`): настоящий
``ValueError: min() arg is empty`` МЕСЯЦАМИ печатался как ``watch_symbol_data_reject``,
то есть ошибка кода выглядела в логе как обычная нехватка рыночных данных. Замеры на трёх
прогонах — 8/18, 6/52, 6/51 отказов — не позволяли отличить одно от другого вообще: и то
и другое приходило одной строкой с одинаковым уровнем.

Цена путаницы несимметрична. Нехватка данных — штатное состояние: символ не прогрет,
план не поспел, венью молчит. Ошибка кода — дефект, который надо чинить, и он не проходит
сам. Свалив их в одну строку, мы получаем лог, в котором дефект неотличим от нормы, — и
он там и жил, пока его не нашли руками.

⚠ РАЗДЕЛЕНИЕ ДЕЛАЕТСЯ ТИПОМ, А НЕ ТЕКСТОМ СООБЩЕНИЯ. Разбирать `repr(exc)` регулярками
пробовать не надо: ``ValueError`` — это и «пустая последовательность» (нехватка данных),
и «неверная единица измерения» (дефект), и различить их по тексту нельзя. Поднимать
:class:`DataNotReady` обязан тот код, который ЗНАЕТ, что данных не хватает.
"""
from __future__ import annotations

__all__ = ["DataNotReady"]


class DataNotReady(Exception):
    """Рыночных данных не хватает для расчёта — это ШТАТНОЕ состояние, а не дефект.

    Поднимать, когда расчёт невозможен ИМЕННО из-за отсутствия/незрелости данных:
    символ не прогрет, план не поспел, окно короче требуемого, венью не ответила.

    ⚠ НЕ поднимать вместо ошибки кода. Опечатка в ключе, неверная единица, рассогласование
    типов — это дефекты, и они обязаны долетать до обработчика как есть, с трассой. Обёртка
    такого исключения в ``DataNotReady`` вернёт ровно тот инцидент, ради которого модуль и
    заведён: дефект, замаскированный под норму.

    Args:
        reason: Короткий машинный повод (``"kline_1h_absent"``, ``"window_too_short"``).
            Идёт в лог отдельным полем, поэтому пригоден для группировки.
        detail: Человеческое пояснение, если повода мало.
    """

    def __init__(self, reason: str, *, detail: str | None = None) -> None:
        self.reason = str(reason)
        self.detail = detail
        super().__init__(f"{self.reason}: {detail}" if detail else self.reason)
