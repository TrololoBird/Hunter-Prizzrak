"""Общий вывод для верификаторов: сообщить о НЕПОЛНОМ покрытии рядом с вердиктом.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Блок «сколько пар символ/ТФ не загрузилось» появился одновременно
в пяти скриптах (`verify_signal_geometry`, `verify_zone_geometry`, `verify_zone_handoff`,
`verify_value_area_stability`, `score_vs_razbor`) — и SonarCloud справедливо показал
4.8% дублирования на новом коде при пороге 3%. Дубль здесь опаснее обычного: формулировка
вердикта и есть предмет правки, а разъехавшиеся копии дадут пять разных обещаний об одном
и том же.

Почему вообще нужен: верификатор, молча пропустивший часть входа, печатает «нарушений не
найдено» — утверждение шире сделанного ровно на пропущенное. Молчание в проверяющем коде
выдаёт СЕРТИФИКАТ, поэтому оно хуже, чем молчание в боевом.
"""
from __future__ import annotations

from collections.abc import Callable, Sequence

_MAX_SHOWN = 20


def report_skipped(
    skipped: Sequence[str],
    *,
    total: int | None = None,
    say: Callable[[str], None] = print,
    bullet: str = "   ",
) -> None:
    """Напечатать блок о неполном покрытии. Ничего не печатает, если пропусков нет.

    Args:
        skipped: Строки вида ``"SYMBOL/tf: ПричинаОшибки"``.
        total: Плановое число единиц покрытия, если известно, — тогда печатается доля.
            ``None`` означает «знаменатель неизвестен», и он НЕ выдумывается.
        say: Куда печатать. По умолчанию ``print``; скрипты, копящие отчёт в файл,
            передают свою функцию (см. ``verify_value_area_stability.py``).
        bullet: Отступ строк списка — в markdown-отчётах нужен ``"  - "``, в консоли пробелы.
    """
    if not skipped:
        return
    head = f"ПОКРЫТИЕ НЕПОЛНОЕ — не загружено пар символ/ТФ: {len(skipped)}"
    if total:
        head += f" из {total}"
    say("")
    say(head)
    for s in skipped[:_MAX_SHOWN]:
        say(f"{bullet}{s}")
    if len(skipped) > _MAX_SHOWN:
        say(f"{bullet}… и ещё {len(skipped) - _MAX_SHOWN}")


def verdict_scope(skipped: Sequence[str]) -> str:
    """Оговорка к вердикту: пусто при полном покрытии, иначе — честная оговорка.

    Ставится в ту же строку, где скрипт объявляет результат, чтобы «нарушений не найдено»
    и «на загруженной части» нельзя было прочитать порознь.
    """
    return " НА ЗАГРУЖЕННОЙ ЧАСТИ (см. пропуски выше)" if skipped else ""


__all__ = ["report_skipped", "verdict_scope"]
