#!/bin/sh
# PostToolUse-хук: `ruff check --fix` по ОДНОМУ отредактированному файлу.
#
# Почему отдельный файл, а не строка в settings.json. Прежняя редакция была однострочным
# `jq | read | case … || true` прямо в JSON, с двумя захардкоженными абсолютными путями
# (`/Users/tonyaleksandrov/...`) — то есть ломалась в любом другом чекауте, а `|| true`
# глушил ЛЮБУЮ ошибку, включая «ruff не найден». Хук, который не может сообщить о поломке,
# неотличим от отсутствующего.
#
# `--unfixable F401` осознанно: автоснос неиспользуемых импортов гонится с парными правками
# (импорт добавлен, потребитель ещё не написан) — про F401 ruff только сообщает.
#
# Контракт хука: stdin — JSON события, выход 0 = успех, 2 = блокировать. Здесь правка уже
# применена, блокировать нечего, поэтому не-нулевой код возвращается только когда сам
# инструмент сломан, — и тогда это ВИДНО, а не проглочено.
set -eu

ROOT="${CLAUDE_PROJECT_DIR:-$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)}"

# Раскладка venv зависит от платформы: POSIX кладёт бинарь в bin/, Windows — в Scripts/ с .exe.
# Прежняя редакция знала только про bin/, поэтому на Windows хук падал на проверке ниже с
# «ruff не найден» — то есть линт правок молча не выполнялся ни разу (замер 2026-07-30).
RUFF="$ROOT/.venv/bin/ruff"
[ -x "$RUFF" ] || RUFF="$ROOT/.venv/Scripts/ruff.exe"

file="$(jq -r '.tool_input.file_path // .tool_response.filePath // empty')"
[ -n "$file" ] || exit 0
case "$file" in *.py) ;; *) exit 0 ;; esac
[ -f "$file" ] || exit 0

if [ ! -x "$RUFF" ]; then
  echo "hook_ruff_fix: ruff не найден по пути $RUFF — линт правок НЕ выполняется" >&2
  exit 1
fi

# ruff отдаёт ненулевой код при оставшихся нарушениях — это нормальный отчёт, не поломка хука.
"$RUFF" check --fix --unfixable F401 "$file" || true
