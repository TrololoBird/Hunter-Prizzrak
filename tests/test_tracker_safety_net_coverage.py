"""Гард: открытая позиция ОБЯЗАНА быть покрыта хотя бы одной сетью мониторинга.

Дефект, который тест закрывает (измерен на живом состоянии 2026-07-27). Тик обрабатывает
только ПРОГРЕТЫЕ символы (`ordered` фильтрует переданный список по warm-set движка), а тикерная
сеть безопасности вычитала активные символы из `set(symbols)` — из ВСЕГО переданного списка.
Символ, который есть в юниверсе, но не прогрет, выпадал из обеих сетей одновременно:

* тик его пропускал — нет в warm-set;
* тикерная сеть пропускала — он «уже виден» в `seen`.

Замер: из 12 открытых сигналов проверялись 2 (оба пиннед). У остальных десяти `last_checked_at`
отставал на 3.1–8.3 часа, а у шести в точности совпадал с `opened_at` — то есть позицию
проверили один раз при открытии и больше никогда. ENAUSDT был в `watch_universe`, но не в
warm-set из семи символов. Прямой прогон `reconcile_active_from_ticker` по тому же состоянию
обновил все 12 записей и выдал 2 события, одно `invalidate`.

Здесь проверяется СВОЙСТВО покрытия на арифметике множеств, потому что именно она и разъехалась.
"""
from __future__ import annotations

import pathlib
import re


def _tick_source() -> str:
    return pathlib.Path("hunt_core/runtime/cycle/_cycle_tick.py").read_text(encoding="utf-8")


def test_safety_net_subtracts_checked_not_passed() -> None:
    """`missing_active` обязан считаться от ПРОВЕРЕННЫХ символов, а не от переданных.

    `set(symbols)` — это весь переданный список, включая непрогретые, которые тик не трогал.
    Вычитание его из активных и создавало дыру.
    """
    src = _tick_source()
    assert "missing_active = active_syms - checked" in src, (
        "сеть безопасности снова считается не от проверенных символов — "
        "непрогретая открытая позиция останется без мониторинга"
    )
    assert "missing_active = active_syms - seen" not in src


def test_checked_is_built_from_symbols_with_a_live_view() -> None:
    """«Проверен» = для символа собралcя view. Список `ordered` сам по себе этого не гарантирует.

    Символ может попасть в `ordered` (он прогрет) и всё равно не получить view — таймаут,
    исключение, `not_ready`. Такой символ SL/TP-проверку не прошёл и обязан достаться сети.
    """
    src = _tick_source()
    m = re.search(r"checked\s*=\s*\{(.+?)\}", src, re.S)
    assert m, "не найдено построение множества `checked`"
    body = m.group(1)
    assert "ordered" in body, "`checked` обязан строиться из фактически обработанных символов"
    assert "settled" in body and "is not None" in body, (
        "`checked` обязан требовать собранный view, а не просто присутствие в `ordered`"
    )


def test_orphan_net_still_uses_the_full_universe() -> None:
    """Вторая сеть (сироты) намеренно остаётся на `seen` — у неё другая задача.

    Она ловит символы, ВЫШЕДШИЕ из вотчлиста. Если и её перевести на `checked`, обе сети
    начнут делать одно и то же, а зазор «в юниверсе, но не прогрет» так и останется
    закрытым только одной из них — то есть без запаса.
    """
    src = _tick_source()
    assert "seen_symbols=seen" in src, (
        "сеть сирот должна продолжать работать от полного списка юниверса"
    )
    assert re.search(r"^\s*seen = set\(symbols\)", src, re.M), "`seen` должен остаться полным списком"
